"""Write patcher/vf1_unicode18.py, the compact Unicode 18.0 tables the patcher and both Unicode DLLs use, from the
Unicode Character Database files scripts/fetch_unicode18.py downloaded and checked (their SHA-256s are recorded in
the module, and data/unicode18/LICENSE-Unicode.txt is the Unicode licence the data is used under).

Python's own unicodedata (16.0 in Python 3.14) and Windows' ICU are older than 18.0, so the tables that depend on
the Unicode version are read from 18.0 itself:

* EXTENDER_MARKS: general category Mn, Mc and Me (the cluster rule's marks: vf1_text.EXTENDER_RANGES, and from it
  native/vf1text/extenders.inc);
* EMOJI_PRESENTATION: the Emoji_Presentation property (vf1_emoji, and from it native/vf1text/emoji.inc);
* ASSIGNED: every assigned code point (the coverage test: each one gets a glyph).

Usage:  python scripts/build_vf1_unicode18.py --ucd C:/vf1/dl-u18-<date>/ucd18 [--check]
"""
from __future__ import annotations

import argparse
import hashlib
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "patcher" / "vf1_unicode18.py"
LICENSE = ROOT / "data" / "unicode18" / "LICENSE-Unicode.txt"
FILES = ("ucd/UnicodeData.txt", "ucd/emoji/emoji-data.txt")


def ranges(cps) -> list[tuple[int, int]]:
    out: list[list[int]] = []
    for cp in sorted(set(cps)):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [(a, b) for a, b in out]


def unicode_data(text: str):
    """(code point, general category) of every assigned code point (the First/Last ranges expanded)."""
    first = None
    for line in text.splitlines():
        if not line.strip():
            continue
        f = line.split(";")
        cp, name, cat = int(f[0], 16), f[1], f[2]
        if name.endswith(", First>"):
            first = cp
            continue
        if name.endswith(", Last>") and first is not None:
            for c in range(first, cp + 1):
                yield c, cat
            first = None
            continue
        yield cp, cat


def property_cps(text: str, prop: str):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        span, name = (s.strip() for s in line.split(";")[:2])
        if name != prop:
            continue
        a, _, b = span.partition("..")
        yield from range(int(a, 16), int(b or a, 16) + 1)


def table(name: str, rs: list[tuple[int, int]], per_line: int = 6) -> str:
    lines = [f"{name}: tuple[tuple[int, int], ...] = ("]
    row = []
    for a, b in rs:
        row.append(f"(0x{a:X}, 0x{b:X})")
        if len(row) == per_line:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append(")")
    return "\n".join(lines)


def render(ucd: Path) -> str:
    data = {name: (ucd / name).read_bytes() for name in FILES}
    cats = list(unicode_data(data["ucd/UnicodeData.txt"].decode("utf-8")))
    marks = ranges(cp for cp, cat in cats if cat in ("Mn", "Mc", "Me"))
    assigned = ranges(cp for cp, _cat in cats)
    surrogates_and_controls = ranges(cp for cp, cat in cats if cat in ("Cs", "Cc"))
    emoji = ranges(property_cps(data["ucd/emoji/emoji-data.txt"].decode("utf-8"), "Emoji_Presentation"))
    sources = "\n".join(f'    "{n}": "{hashlib.sha256(d).hexdigest().upper()}",' for n, d in data.items())
    return f'''"""Unicode 18.0.0 tables (generated by scripts/build_vf1_unicode18.py from the Unicode Character Database; do not
edit). The data is used under the Unicode License v3 (data/unicode18/LICENSE-Unicode.txt)."""
from __future__ import annotations

VERSION = "18.0.0"
# the source files, https://www.unicode.org/Public/18.0.0/ + name, and their SHA-256
SOURCES = {{
{sources}
}}

# general category Mn, Mc and Me: the marks a whole character (grapheme cluster) takes after its letter
{table("EXTENDER_MARKS", marks)}

# Emoji_Presentation (emoji-data.txt): shown as a picture by default
{table("EMOJI_PRESENTATION", emoji)}

# every assigned code point
{table("ASSIGNED", assigned)}

# the assigned code points that are never drawn as a glyph: surrogates and C0 / C1 controls
{table("NOT_DRAWN", surrogates_and_controls)}
'''


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd", type=Path, required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render(a.ucd)
    if a.check:
        ok = OUT.read_text(encoding="utf-8") == text
        print("up to date" if ok else "out of date")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    LICENSE.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(a.ucd / "license.txt", LICENSE)
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
