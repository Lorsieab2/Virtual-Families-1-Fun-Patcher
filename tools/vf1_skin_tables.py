"""Writes native/vf1skin/skin_tables.h: the numbers of the skin tone recolour, for vf1skin.dll.

The method is the Virtual Villagers Fun Patcher's (the owner, 2026-11-28: VF1's tones look exactly like VV's), as
patcher/vf1_skin_art.py has it: per row of cells, the skin's middle and reach (2nd, 50th and 98th percentiles of its
OKLab lightness), the tone's hue and chroma in OKLCh, the art's own shading kept as lightness offsets at SHADING
strength, never ashy. This file turns that module's tone table and constants into C; it needs no game file.
Run it again after changing a tone:  python tools/vf1_skin_tables.py   (--check: only compare with the header)
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "patcher"))
import vf1_skin_art as art  # noqa: E402

# vf1_skin_art's (the Virtual Villagers patcher's) own OKLab matrices, as written there.
TO_LMS = ((0.4122214708, 0.5363325363, 0.0514459929), (0.2119034982, 0.6806995451, 0.1073969566),
          (0.0883024619, 0.2817188376, 0.6299787005))
TO_LAB = ((0.2104542553, 0.7936177850, -0.0040720468), (1.9779984951, -2.4285922050, 0.4505937099),
          (0.0259040371, 0.7827717662, -0.8086757660))
LAB_TO_LMS = ((1.0, 0.3963377774, 0.2158037573), (1.0, -0.1055613458, -0.0638541728),
              (1.0, -0.0894841775, -1.2914855480))
LMS_TO_LINEAR = ((4.0767416621, -3.3077115913, 0.2309699292), (-1.2684380046, 2.6097574011, -0.3413193965),
                 (-0.0041960863, -0.7034186147, 1.7076147010))
HEADER = ROOT / "native" / "vf1skin" / "skin_tables.h"


def decode(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def table() -> str:
    d = lambda v: repr(float(v))
    out = ["// GENERATED by tools/vf1_skin_tables.py from patcher/vf1_skin_art.py. Do not edit.", "#pragma once", "",
           f"#define SKIN_TONE_COUNT {len(art.TONE_TABLE)}",
           f"static const double SkinFloor = {d(art.L_FLOOR)}, SkinCeil = {d(art.L_CEIL)}, SkinGive = {d(art.GIVE)};",
           f"static const double SkinShading = {d(art.SHADING)}, SkinChromaFloor = {d(art.CHROMA_FLOOR)}, "
           f"SkinShadowChroma = {d(art.SHADOW_CHROMA)};",
           f"static const unsigned SkinPercentiles[3] = {{ {', '.join(str(q) for q in art.PERCENTILES)} }};", "",
           "// lightness, chroma, cos(hue), sin(hue) of each tone's lit mid-skin",
           "struct SkinTone { const char *name; double L, chroma, cosHue, sinHue; };",
           "static const SkinTone SkinTones[SKIN_TONE_COUNT + 1] = {", '    { "Game\'s own", 0, 0, 0, 0 },']
    for name, _hex, L, c, hue in art.TONE_TABLE:
        h = math.radians(hue)
        out.append(f'    {{ "{name}", {d(L)}, {d(c)}, {d(math.cos(h))}, {d(math.sin(h))} }},')
    out.append("};")
    for name, m in (("SkinToLms", TO_LMS), ("SkinToLab", TO_LAB), ("SkinLabToLms", LAB_TO_LMS),
                    ("SkinLmsToLinear", LMS_TO_LINEAR)):
        out.append(f"static const double {name}[3][3] = {{")
        out.extend("    { " + ", ".join(d(v) for v in row) + " }," for row in m)
        out.append("};")
    out.append("// sRGB 0..255 as linear light")
    out.append("static const double SkinLinear[256] = {")
    for k in range(0, 256, 4):
        out.append("    " + ", ".join(d(art._LINEAR[v]) for v in range(k, k + 4)) + ",")
    out.append("};")
    out.append("// the linear light at which the stored value becomes v (v = 1..255): the stored value is how many "
               "of these are not above the light")
    out.append("static const double SkinEncode[255] = {")
    steps = [decode((v - 0.5) / 255) for v in range(1, 256)]
    for k in range(0, 255, 4):
        out.append("    " + ", ".join(d(v) for v in steps[k:k + 4]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if "--check" in sys.argv[1:]:
        sys.exit(0 if HEADER.read_text(encoding="utf-8") == table() else 1)
    HEADER.write_text(table(), encoding="utf-8", newline="\n")
    print(HEADER)
