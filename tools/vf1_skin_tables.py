"""Writes native/vf1skin/skin_tables.h: the numbers of the skin tone recolour, for vf1skin.dll.

The method is the approved one (the Skin Tones workbench's vfskin.py: replace the skin's colour with the tone
in OKLCh, the art's own shading kept as lightness offsets, never ashy).  This file holds the tone table and
the constants in ONE place and turns them into C tables; it needs only the standard library, and no game
file.  Run it again after changing a tone:  python tools/vf1_skin_tables.py
"""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# The owner's ten tones (2026-11-26), light to dark: each colour is where the lit mid-skin lands.
TONES = (
    ("Porcelain", "#fbe3d7"), ("Fair", "#f0ccaa"), ("Light golden", "#e2b88c"), ("Light olive", "#cea878"),
    ("Copper", "#cc8a5a"), ("Warm brown", "#b0784e"), ("Medium brown", "#92623e"), ("Deep brown", "#724c32"),
    ("Dark", "#523423"), ("Ebony", "#322017"),
)
L_FLOOR, L_CEIL, GIVE, SHADOW_CHROMA = 0.16, 0.985, 0.3, 0.22
# (mid, down, up, knee, keep): the game's stock lit mid-skin (OKLab lightness), how far the art goes below
# and above it, and the blown-out range that keeps only `keep` of its spread (vfskin.ANCHOR).
ANCHOR = {"VF1": (0.86, 0.45, 0.06, 0.86, 0.45), "VF2": (0.80, 0.31, 0.16, 2.0, 1.0)}

OK1 = ((0.4122214708, 0.5363325363, 0.0514459929), (0.2119034982, 0.6806995451, 0.1073969566),
       (0.0883024619, 0.2817188376, 0.6299787005))
OK2 = ((0.2104542553, 0.7936177850, -0.0040720468), (1.9779984951, -2.4285922050, 0.4505937099),
       (0.0259040371, 0.7827717662, -0.8086757660))


def inverse(m):
    (a, b, c), (d, e, f), (g, h, i) = m
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    return (((e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det),
            ((f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det),
            ((d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det))


def linear(v: int) -> float:
    return decode(v / 255)


def decode(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def oklch(text: str):
    lin = [linear(int(text[i:i + 2], 16)) for i in (1, 3, 5)]
    lms = [sum(OK1[r][k] * lin[k] for k in range(3)) ** (1 / 3) for r in range(3)]
    L, a, b = (sum(OK2[r][k] * lms[k] for k in range(3)) for r in range(3))
    return L, math.hypot(a, b), math.atan2(b, a)


def tone_scales(L, down, up):
    s_down = max(min(1.0, (L - L_FLOOR) / max(down, 1e-6)), 0.0)
    s_up = max(min(1.0, (L_CEIL - L) / max(up, 1e-6)), 0.0)
    more_up = min(1 + GIVE * (1 - s_down), (L_CEIL - L) / max(up, 1e-6))
    more_down = min(1 + GIVE * (1 - s_up), (L - L_FLOOR) / max(down, 1e-6))
    return (more_down if s_up < 1 else s_down), (more_up if s_down < 1 else s_up)


def table(game: str) -> str:
    mid, down, up, knee, keep = ANCHOR[game]
    d = lambda v: repr(float(v))
    out = [f"// GENERATED by tools/vf1_skin_tables.py ({game}). Do not edit.", "#pragma once", "",
           f"#define SKIN_TONE_COUNT {len(TONES)}",
           f"static const double SkinMid = {d(mid)}, SkinDown = {d(max(down, 1e-6))}, SkinKnee = {d(knee)}, "
           f"SkinKeep = {d(keep)};",
           f"static const double SkinFloor = {d(L_FLOOR)}, SkinCeil = {d(L_CEIL)}, SkinShadowChroma = "
           f"{d(SHADOW_CHROMA)};", "",
           "// lightness, chroma, cos(hue), sin(hue), scale below the middle, scale above it",
           "struct SkinTone { const char *name; double L, chroma, cosHue, sinHue, down, up; };",
           "static const SkinTone SkinTones[SKIN_TONE_COUNT + 1] = {", '    { "Game\'s own", 0, 0, 0, 0, 0, 0 },']
    for name, text in TONES:
        L, c, h = oklch(text)
        s_down, s_up = tone_scales(L, down, up)
        out.append(f'    {{ "{name}", {d(L)}, {d(c)}, {d(math.cos(h))}, {d(math.sin(h))}, {d(s_down)}, {d(s_up)} }},')
    out.append("};")
    for name, m in (("SkinToLms", OK1), ("SkinToLab", OK2), ("SkinLabToLms", inverse(OK2)),
                    ("SkinLmsToLinear", inverse(OK1))):
        out.append(f"static const double {name}[3][3] = {{")
        out.extend("    { " + ", ".join(d(v) for v in row) + " }," for row in m)
        out.append("};")
    out.append("// sRGB 0..255 as linear light")
    out.append("static const double SkinLinear[256] = {")
    for k in range(0, 256, 4):
        out.append("    " + ", ".join(d(linear(v)) for v in range(k, k + 4)) + ",")
    out.append("};")
    out.append("// the linear light at which the stored value becomes v (v = 1..255): the stored value is how many "
               "of these are not above the light")
    out.append("static const double SkinEncode[255] = {")
    steps = [decode((v - 0.5) / 255) for v in range(1, 256)]
    for k in range(0, 255, 4):
        out.append("    " + ", ".join(d(v) for v in steps[k:k + 4]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    path = ROOT / "native" / "vf1skin" / "skin_tables.h"
    path.write_text(table("VF1"), encoding="utf-8", newline="\n")
    print(path)
