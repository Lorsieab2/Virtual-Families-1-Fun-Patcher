"""Which whole characters are emoji shown as pictures (colour emoji): the one rule of the patcher's tools and of
vf1text.dll / vf1font.dll (native/vf1text/emoji.inc is the same table, written by scripts/build_vf1_text_tables.py
and checked by tests/test_colour_emoji.py).

A whole character (grapheme cluster, vf1_text.clusters) is a colour emoji when nothing in it asks for text
presentation (U+FE0E) and
* a code point of it has Emoji_Presentation (an emoji shown as a picture by default: faces, animals, flags'
  regional indicators, skin tones), or
* it holds U+FE0F (emoji presentation asked for, as in ❤️ or ☺️), a keycap U+20E3 (1️⃣), a skin tone
  (U+1F3FB..U+1F3FF) or a tag character (U+E0020..U+E007F, subdivision flags).
A joined sequence (U+200D) is a colour emoji when any of its parts is.

EMOJI_PRESENTATION_RANGES is Unicode 18.0's Emoji_Presentation property (vf1_unicode18, from the Unicode Character
Database; Windows' own ICU is older), fixed so the patcher and the DLLs never disagree. `build_emoji_presentation`
reads the property from Windows' ICU, which the tests compare with (every emoji ICU knows is in the table).
"""
from __future__ import annotations

import vf1_unicode18

__all__ = ["EMOJI_PRESENTATION_RANGES", "is_emoji_presentation", "is_colour_emoji", "emoji_table_c",
           "build_emoji_presentation"]

# Unicode 18.0's Emoji_Presentation (emoji-data.txt), the bundled table (vf1_unicode18).
EMOJI_PRESENTATION_RANGES: tuple[tuple[int, int], ...] = vf1_unicode18.EMOJI_PRESENTATION

TEXT_PRESENTATION = 0xFE0E
EMOJI_PRESENTATION_SELECTOR = 0xFE0F
KEYCAP = 0x20E3


def is_emoji_presentation(cp: int) -> bool:
    lo, hi = 0, len(EMOJI_PRESENTATION_RANGES) - 1
    while lo <= hi:
        mid = (lo + hi) // 2
        a, b = EMOJI_PRESENTATION_RANGES[mid]
        if cp < a:
            hi = mid - 1
        elif cp > b:
            lo = mid + 1
        else:
            return True
    return False


def _asks_for_colour(cp: int) -> bool:
    return cp == EMOJI_PRESENTATION_SELECTOR or cp == KEYCAP or 0x1F3FB <= cp <= 0x1F3FF or 0xE0020 <= cp <= 0xE007F


def is_colour_emoji(cluster: str) -> bool:
    """Whether one whole character is drawn as a colour picture (the DLLs' IsColourEmoji)."""
    cps = [ord(c) for c in cluster]
    if TEXT_PRESENTATION in cps:
        return False
    return any(is_emoji_presentation(cp) or _asks_for_colour(cp) for cp in cps)


def build_emoji_presentation() -> tuple[tuple[int, int], ...]:
    """The Emoji_Presentation ranges from Windows' ICU (icu.dll), to refresh EMOJI_PRESENTATION_RANGES; None of
    them without it."""
    import ctypes
    lib = ctypes.WinDLL("icu.dll")
    lib.u_hasBinaryProperty.argtypes = [ctypes.c_int, ctypes.c_int]
    lib.u_hasBinaryProperty.restype = ctypes.c_ubyte              # UBool
    ranges: list[list[int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if lib.u_hasBinaryProperty(cp, 58):                        # UCHAR_EMOJI_PRESENTATION
            if ranges and ranges[-1][1] == cp - 1:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
    return tuple((a, b) for a, b in ranges)


def emoji_table_c() -> str:
    """The ranges as a C table, for native/vf1text/emoji.inc (generated, never edited by hand)."""
    lines = [
        "// Generated by scripts/build_vf1_text_tables.py from patcher/vf1_emoji.py (EMOJI_PRESENTATION_RANGES).",
        "// Do not edit: the patcher's tools and vf1text.dll must pick the same colour emoji.",
        f"static const unsigned EmojiPresentationRanges[{len(EMOJI_PRESENTATION_RANGES)}][2] = {{",
    ]
    row: list[str] = []
    for a, b in EMOJI_PRESENTATION_RANGES:
        row.append(f"{{0x{a:X},0x{b:X}}}")
        if len(row) == 6:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"
